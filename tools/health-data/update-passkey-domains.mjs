// Regenerates packages/vault-client/src/data/passkey-domains.ts from a downloaded copy of the
// passkeys directory (see README.md). The download is data: only well-formed names are kept.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { registrableDomain } from '../../packages/vault-client/src/tools/url.ts';

const source = process.argv[2];
if (!source) {
  console.error('usage: node tools/health-data/update-passkey-domains.mjs <supported.json>');
  process.exit(1);
}
const output = fileURLToPath(new URL('../../packages/vault-client/src/data/passkey-domains.ts', import.meta.url));
const NAME = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;

const directory = JSON.parse(readFileSync(source, 'utf8'));
const domains = [...new Set(Object.keys(directory).filter((name) => NAME.test(name)).map(registrableDomain))].sort();
if (domains.length < 100) throw new Error(`only ${domains.length} domains: is this the right file?`);

const lines = [];
for (let i = 0; i < domains.length; i += 6) lines.push(`  ${domains.slice(i, i + 6).map((d) => `'${d}'`).join(', ')},`);
const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  output,
  `// Registrable domains of sites that accept passkeys, used by the health report's "passkey available"
// check. Generated by tools/health-data/update-passkey-domains.mjs on ${date}; don't edit by hand.
// Source: the passkeys directory (passkeys.2fa.directory) by 2factorauth, CC BY 4.0, reduced to
// registrable domains.

export const PASSKEY_DOMAINS: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`,
);
console.log(`${domains.length} domains`);
