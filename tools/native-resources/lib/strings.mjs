// The messages as an iOS String Catalog, Android string resources and Swift accessors.

import { toFormat } from './messages.mjs';
import { androidName, identifier as identifierOf, swiftName, uniqueNames } from './names.mjs';

export const GENERATED_NOTE = 'Generated by tools/native-resources from apps/web/src/i18n/{en,ar}.ts and apps/web/src/i18n/phone.ts. Do not edit: change the catalogs, then run `node tools/native-resources/generate.mjs`.';

// iOS ---------------------------------------------------------------------------------------------

export const iosSpecifier = (arg) => `%${arg.position}$${arg.kind === 'int' ? 'lld' : '@'}`;

const unit = (value) => ({ stringUnit: { state: 'translated', value } });

/**
 * A counted message whose only argument is the count, shown in the general form, can vary the
 * whole string by plural. Any other counted message (more than one argument, or a count the text
 * never shows) puts the forms in a `count` substitution, so Xcode knows which argument picks the
 * form; the other arguments keep their positions inside each form.
 */
export function usesSubstitution(message) {
  return message.plural && !(message.args.length === 1 && /\{count\}/.test(message.text.en.other));
}

function iosLocalization(message, forms) {
  const format = (text) => toFormat(text, message.args, iosSpecifier);
  if (!message.plural) return unit(format(forms));
  const plural = (spec) => Object.fromEntries(Object.entries(forms).map(([c, text]) => [c, unit(toFormat(text, message.args, spec))]));
  if (!usesSubstitution(message)) return { variations: { plural: plural(iosSpecifier) } };
  const count = message.args.find((a) => a.name === 'count');
  return {
    stringUnit: { state: 'translated', value: '%#@count@' },
    substitutions: {
      count: {
        argNum: count.position,
        formatSpecifier: 'lld',
        variations: { plural: plural((arg) => (arg.name === 'count' ? '%arg' : iosSpecifier(arg))) },
      },
    },
  };
}

/** Xcode's own layout: keys sorted, two-space indent, `" : "`. */
function xcodeJson(value) {
  const sort = (v) =>
    Array.isArray(v) ? v.map(sort) : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sort(v[k])])) : v;
  return `${JSON.stringify(sort(value), null, 2).replace(/^(\s*"(?:[^"\\]|\\.)*"): /gm, '$1 : ')}\n`;
}

export function xcstrings(messages, sourceLanguage = 'en') {
  const strings = {};
  for (const message of messages) {
    const localizations = {};
    for (const [locale, forms] of Object.entries(message.text)) localizations[locale] = iosLocalization(message, forms);
    strings[message.key] = { extractionState: 'manual', localizations };
  }
  return xcodeJson({ sourceLanguage, strings, version: '1.0' });
}

// Android -----------------------------------------------------------------------------------------

export const androidSpecifier = (arg) => `%${arg.position}$${arg.kind === 'int' ? 'd' : 's'}`;

/** Text as the inside of an Android `<string>` or `<item>`. */
export function androidEscape(text) {
  let out = text
    .replaceAll('\\', '\\\\')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t');
  // aapt2 collapses runs of spaces and trims the ends; escaped spaces survive.
  out = out.replace(/^ +| +$| {2,}/g, (spaces) => '\\u0020'.repeat(spaces.length));
  if (/^[@?]/.test(out)) out = `\\${out}`;
  return out;
}

export function stringsXml(messages, locale) {
  const names = uniqueNames(
    messages.map((m) => m.key),
    androidName,
    'Android resource',
  );
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${GENERATED_NOTE} -->`, '<resources>'];
  for (const message of messages) {
    const forms = message.text[locale];
    if (forms === undefined) continue;
    const name = names.get(message.key);
    const format = (text) => androidEscape(toFormat(text, message.args, androidSpecifier));
    if (!message.plural) {
      // A string without arguments is never formatted, so a `%` in it is just a percent sign.
      const literal = message.args.length === 0 && forms.includes('%') ? ' formatted="false"' : '';
      lines.push(`    <string name="${name}"${literal}>${format(forms)}</string>`);
    } else {
      lines.push(`    <plurals name="${name}">`);
      for (const [category, text] of Object.entries(forms)) lines.push(`        <item quantity="${category}">${format(text)}</item>`);
      lines.push('    </plurals>');
    }
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

// Swift accessors ---------------------------------------------------------------------------------

/** Names `L10n` declares itself, which no catalog group may take. */
const L10N_MEMBERS = ['bundle', 'locale', 'language', 'setLanguage', 'formattingLocale', 'string', 'format'];

/** The messages as a tree of groups: { groups: Map, messages: [] }. */
function tree(messages) {
  const root = { groups: new Map(), messages: [] };
  for (const message of messages) {
    const parts = message.key.split('.');
    let node = root;
    for (const part of parts.slice(0, -1)) {
      if (!node.groups.has(part)) node.groups.set(part, { groups: new Map(), messages: [] });
      node = node.groups.get(part);
    }
    node.messages.push({ name: parts.at(-1), message });
  }
  return root;
}

/** Every group's members (its groups, its messages, and at the top L10n's own) need distinct names. */
function checkScope(node, path, reserved = []) {
  const members = [...reserved.map((r) => `L10n's own ${r}`), ...[...node.groups.keys()].map((g) => `${path}.${g}`), ...node.messages.map((m) => m.message.key)];
  uniqueNames(members, (member) => identifierOf(member.split(/[ .]/).at(-1)), `Swift members of ${path} named`);
  for (const [name, child] of node.groups) checkScope(child, `${path}.${name}`);
}

const swiftType = (arg) => (arg.kind === 'int' ? 'Int' : 'String');
const docLine = (text) => text.replace(/\s+/g, ' ').trim();

function swiftMessage({ name, message }, indent) {
  const id = swiftName(name);
  const english = message.plural ? message.text.en.other : message.text.en;
  const doc = `${indent}/// ${docLine(english)}`;
  const key = JSON.stringify(message.key);
  if (message.args.length === 0) return `${doc}\n${indent}public static var ${id}: String { L10n.string(${key}) }`;
  const params = message.args.map((a) => `${swiftName(a.name)}: ${swiftType(a)}`).join(', ');
  const values = message.args.map((a) => swiftName(a.name)).join(', ');
  return `${doc}\n${indent}public static func ${id}(${params}) -> String { L10n.format(${key}, ${values}) }`;
}

function swiftGroup(node, indent) {
  const out = [];
  for (const m of node.messages) out.push(swiftMessage(m, indent));
  for (const [name, child] of node.groups) {
    out.push(`${indent}public enum ${swiftName(name)} {`, ...swiftGroup(child, `${indent}    `), `${indent}}`);
  }
  return out;
}

export function swiftAccessors(messages) {
  const root = tree(messages);
  checkScope(root, 'L10n', L10N_MEMBERS);
  return `// ${GENERATED_NOTE}
//
// One accessor per message: \`L10n.common.back\`, \`L10n.list.searchPlaceholder(count: 3)\`. Arguments
// are in the order of the format string's positions; counted messages pick their plural form from
// \`count\` through the String Catalog.

import Foundation

public enum L10n {
    /// The bundle strings are read from and the locale they're formatted in. Read through
    /// \`setLanguage(_:)\`, so the two always agree: Foundation picks a plural form by the locale,
    /// not by the bundle's language.
    nonisolated(unsafe) static var bundle: Bundle = .module
    nonisolated(unsafe) static var locale: Locale = formattingLocale(Bundle.module.preferredLocalizations.first ?? "en")

    /// The language strings are shown in: the system's (or the one chosen for the app in Settings)
    /// unless \`setLanguage(_:)\` picked another.
    nonisolated(unsafe) public private(set) static var language: String = Bundle.module.preferredLocalizations.first ?? "en"

    /// Shows strings in \`language\` (\`"en"\`, \`"ar"\`), or the system's language for nil. For a
    /// language chosen in the app: call it before any screen reads a string.
    public static func setLanguage(_ language: String?) {
        let chosen = language.flatMap { lang in Bundle.module.localizations.contains(lang) ? lang : nil }
        let shown = chosen ?? Bundle.module.preferredLocalizations.first ?? "en"
        self.language = shown
        bundle = Bundle.module.path(forResource: shown, ofType: "lproj").flatMap(Bundle.init(path:)) ?? .module
        locale = formattingLocale(shown)
    }

    /// As the web vault formats: the language's plural rules and digit grouping, Western digits.
    static func formattingLocale(_ language: String) -> Locale {
        Locale(identifier: "\\(language)@numbers=latn")
    }

    static func string(_ key: String) -> String {
        bundle.localizedString(forKey: key, value: nil, table: "Localizable")
    }

    static func format(_ key: String, _ arguments: any CVarArg...) -> String {
        format(key, arguments: arguments)
    }

    static func format(_ key: String, arguments: [any CVarArg]) -> String {
        String(format: string(key), locale: locale, arguments: arguments)
    }

${swiftGroup(root, '    ').join('\n')}
}
`;
}
